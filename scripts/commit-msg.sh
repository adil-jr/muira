#!/bin/sh
# Validate a commit message against Conventional Commits 1.0.0.
# Usage: scripts/commit-msg.sh <path-to-commit-msg-file>
set -eu

msg_file=${1:?usage: commit-msg.sh <commit-msg-file>}
max_subject=72
types='feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert'
pattern="^($types)(\\([a-z0-9][a-z0-9._/-]*\\))?!?: [^[:space:]].*$"

# Drop comment lines git adds to the template, then take the first line.
body=$(grep -v '^#' "$msg_file" || true)
subject=$(printf '%s\n' "$body" | sed -n '1p')
second=$(printf '%s\n' "$body" | sed -n '2p')

fail() {
	printf 'commit-msg: %s\n' "$1" >&2
	printf '  got:      "%s"\n' "$subject" >&2
	printf '  expected: <type>(<scope>)?: <description>\n' >&2
	printf '  types:    %s\n' "$(printf '%s' "$types" | tr '|' ' ')" >&2
	printf '  example:  feat(crypto): add Argon2id key derivation\n' >&2
	exit 1
}

# Messages generated by git itself.
case $subject in
'Merge '* | 'Revert "'* | 'fixup! '* | 'squash! '* | 'amend! '*) exit 0 ;;
esac

[ -n "$subject" ] || fail "empty commit message"
printf '%s\n' "$subject" | grep -Eq "$pattern" || fail "subject is not a Conventional Commit"
[ "${#subject}" -le "$max_subject" ] || fail "subject longer than $max_subject characters (${#subject})"
[ -z "$second" ] || fail "second line must be blank (separates subject from body)"
